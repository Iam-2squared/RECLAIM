#!/usr/bin/env python3
"""Build the checked-in mobile payload without changing the supplied viewer.

Developer-only dependency: Pillow 12.3.0. Normal npm/Vercel builds copy the
generated assets and do not require Python or Pillow. Run with --check to verify
the source, non-texture payload, and deterministic generated bytes.
"""

import argparse
import base64
import gzip
import hashlib
import io
import json
import re
from pathlib import Path

from PIL import Image, __version__ as pillow_version


ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "public" / "home-map"
SOURCE = FOLDER / "shiretoko.html"
OUTPUT = FOLDER / "shiretoko-mobile.json.gz"
MANIFEST = FOLDER / "shiretoko-mobile.manifest.json"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def encoded_json(data):
    return json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8")


def build():
    original = SOURCE.read_bytes()
    contract = json.loads((FOLDER / "manifest.json").read_text())
    if digest(original) != contract["runtimeViewer"]["sha256"]:
        raise ValueError("Supplied viewer differs from its verified manifest")
    encoded = re.search(rb"\bconst\s+terrainGzipBase64\s*=\s*[\"']([A-Za-z0-9+/=]+)[\"']", original)
    if not encoded:
        raise ValueError("Supplied viewer has no terrain payload")
    source_gzip = base64.b64decode(encoded[1], validate=True)
    source_json = gzip.decompress(source_gzip)
    if digest(source_json) != contract["sourceData"]["sha256"]:
        raise ValueError("Embedded terrain differs from its verified source")
    data = json.loads(source_json, parse_int=lambda value: -0.0 if value == "-0" else int(value))
    untouched = {key: value for key, value in data.items() if key != "textures"}
    nontexture_hash = digest(encoded_json(untouched))
    source_texture_names = list(data.get("textures", {}))
    textures = {}
    records = []
    for name, entry in data.get("textures", {}).items():
        if "normal" in name.lower():
            continue
        prefix, encoded_image = entry["url"].split(",", 1)
        if not prefix.startswith("data:image/") or ";base64" not in prefix:
            raise ValueError("Expected an embedded source texture")
        image_bytes = base64.b64decode(encoded_image, validate=True)
        with Image.open(io.BytesIO(image_bytes)) as image:
            source_size = list(image.size)
            image = image.convert("RGBA" if "A" in image.getbands() else "RGB")
            image.thumbnail((1024, 1024), Image.Resampling.LANCZOS)
            output = io.BytesIO()
            image.save(output, format="WEBP", quality=78, method=6)
            compressed_image = output.getvalue()
            textures[name] = {**entry, "url": "data:image/webp;base64," + base64.b64encode(compressed_image).decode("ascii")}
            records.append({"name": name, "sourceDimensions": source_size, "dimensions": list(image.size),
                            "sourceBytes": len(image_bytes), "bytes": len(compressed_image), "sha256": digest(compressed_image)})
    data["textures"] = textures
    if digest(encoded_json({key: value for key, value in data.items() if key != "textures"})) != nontexture_hash:
        raise ValueError("Mobile packaging changed non-texture world data")
    mobile_json = encoded_json(data)
    mobile_gzip = gzip.compress(mobile_json, compresslevel=9, mtime=0)
    manifest = {"version": 1, "sourceViewerSha256": digest(original), "sourcePayloadSha256": digest(source_json),
                "nonTextureDataSha256": nontexture_hash, "sourceViewerBytes": len(original), "sourceGzipBytes": len(source_gzip),
                "sourceJsonBytes": len(source_json), "mobileGzipBytes": len(mobile_gzip), "mobileJsonBytes": len(mobile_json),
                "mobileGzipSha256": digest(mobile_gzip), "mobileJsonSha256": digest(mobile_json),
                "textureMaxDimension": 1024, "textureQuality": 78, "pillowVersion": pillow_version,
                "omittedTextures": [name for name in source_texture_names if "normal" in name.lower()],
                "textures": records, "nonTextureDataUnmodified": True}
    return mobile_gzip, (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload, manifest = build()
    if args.check:
        if OUTPUT.read_bytes() != payload or MANIFEST.read_bytes() != manifest:
            raise SystemExit("Mobile payload is stale: run python3 scripts/build-mobile-map.py")
    else:
        OUTPUT.write_bytes(payload)
        MANIFEST.write_bytes(manifest)
    print(json.dumps({"verified": args.check, "bytes": len(payload), "file": str(OUTPUT.relative_to(ROOT))}))
